export interface IdRect {
  readonly x: number;
  readonly y: number;
  readonly width: number;
  readonly height: number;
}

export interface IdFieldDefinition {
  readonly key: string;
  readonly label: string;
  readonly normalizedRegions: readonly IdRect[];
  readonly labelAnchors: readonly string[];
  readonly stopAnchors: readonly string[];
  readonly psm: 'SINGLE_LINE' | 'SINGLE_WORD' | 'SINGLE_BLOCK' | 'RAW_LINE' | 'SPARSE_TEXT';
  readonly whitelist?: string;
  readonly blacklist?: string;
  readonly fieldType: IdFieldType;
  readonly required: boolean;
  readonly sensitive?: boolean;
  readonly minConfidenceForAutoFill: number;
}

export interface IdPrivacyRules {
  readonly excludedSensitiveFields: readonly string[];
  readonly retainRawImageByDefault: boolean;
  readonly allowBiometricProfiling: boolean;
  readonly complianceNote?: string;
}

export interface IdTemplate {
  readonly id: string;
  readonly documentFamily: string;
  readonly displayName: string;
  readonly categoryKey: GovernmentIdCategory;
  readonly issuer: string;
  readonly version: string;
  readonly side: 'front' | 'back' | 'data-page' | 'document';
  readonly aspectRatio: { readonly target: number; readonly tolerance: number };
  readonly classificationAnchors: readonly string[];
  readonly negativeAnchors?: readonly string[];
  readonly requiredVisualFeatures: readonly ('portrait' | 'qr' | 'barcode' | 'pdf417' | 'mrz' | 'headerLogo')[];
  readonly fields: readonly IdFieldDefinition[];
  readonly crossSideRules?: readonly string[];
  readonly privacyRules?: IdPrivacyRules;
}

