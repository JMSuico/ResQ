export const getAllIdTemplates = (): readonly IdTemplate[] => ID_TEMPLATE_CATALOGUE;

export const getIdTemplateById = (templateId: string): IdTemplate | undefined =>
  ID_TEMPLATE_CATALOGUE.find((t) => t.id.toUpperCase() === templateId.trim().toUpperCase());

export const getTemplatesByCategory = (
  category: GovernmentIdCategory,
  side?: DocumentSide
): readonly IdTemplate[] =>
  ID_TEMPLATE_CATALOGUE.filter(
    (t) => t.categoryKey === category && (!side || side === 'unknown' || t.side === side)
  );

export const getTemplatesByFamily = (
  documentFamily: string,
  side?: DocumentSide
): readonly IdTemplate[] =>
  ID_TEMPLATE_CATALOGUE.filter(
    (t) =>
      t.documentFamily.toUpperCase() === documentFamily.trim().toUpperCase() &&
      (!side || side === 'unknown' || t.side === side)
  );

